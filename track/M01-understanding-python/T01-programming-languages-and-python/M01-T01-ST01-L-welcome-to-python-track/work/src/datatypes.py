#int
a = 10
print(type(a),a)

#float
a = 10.5
print(type(a),a)

#bool
a = True # False
print(type(a),a)

#str
d = "Hello" # '' or "" or """
print(type(d),d)

#list
e = [1 , 2, 3]
print(type(e),e)

#tuple
f = (1 , 2, 3)
print(type(f),f)

#set
g = {1 , 2, 3}
print(type(g),g)

#dict
h = {1 : "one" , 2 : "two" , 3 : "three"}
print(type(h),h)

#complex
i = 1 + 2j
print(type(i),i)

# None
is_valid = None
print(type(is_valid),is_valid)
    